package org.trex.jdbc;

import com.sun.jna.Pointer;

import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLClientInfoException;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.sql.Statement;
import java.util.Collections;
import java.util.Map;
import java.util.Properties;
import java.util.concurrent.Executor;

final class TrexsqlConnection extends BaseConnection {

    private final String url;
    private final Pointer db;
    private boolean autoCommit = true;
    private boolean closed;

    TrexsqlConnection(String url, TrexsqlDriver.Target target) throws SQLException {
        this.url = url;
        this.db = NativeEngine.openSession();
        if (target.isRemote()) {
            try {
                NativeEngine.execute(db, target.connectSql());
            } catch (SQLException e) {
                NativeEngine.close(db);
                throw new SQLException("trexsql: could not connect to " + target.host + ": " + e.getMessage(), e);
            }
        }
    }

    String url() {
        return url;
    }

    void checkOpen() throws SQLException {
        if (closed) {
            throw new SQLException("trexsql: connection is closed");
        }
    }

    void execute(String sql) throws SQLException {
        checkOpen();
        NativeEngine.execute(db, sql);
    }

    NativeEngine.Rows query(String sql) throws SQLException {
        checkOpen();
        return NativeEngine.query(db, sql);
    }

    @Override
    public Statement createStatement() throws SQLException {
        checkOpen();
        return new TrexsqlStatement(this, null);
    }

    @Override
    public Statement createStatement(int resultSetType, int resultSetConcurrency) throws SQLException {
        requireForwardReadOnly(resultSetType, resultSetConcurrency);
        return createStatement();
    }

    @Override
    public Statement createStatement(int resultSetType, int resultSetConcurrency, int holdability) throws SQLException {
        return createStatement(resultSetType, resultSetConcurrency);
    }

    @Override
    public PreparedStatement prepareStatement(String sql) throws SQLException {
        checkOpen();
        return new TrexsqlStatement(this, sql);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency) throws SQLException {
        requireForwardReadOnly(resultSetType, resultSetConcurrency);
        return prepareStatement(sql);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency, int holdability)
            throws SQLException {
        return prepareStatement(sql, resultSetType, resultSetConcurrency);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException {
        if (autoGeneratedKeys != Statement.NO_GENERATED_KEYS) {
            throw BaseConnection.unsupported("generated keys");
        }
        return prepareStatement(sql);
    }

    private static void requireForwardReadOnly(int type, int concurrency) throws SQLException {
        if (type != ResultSet.TYPE_FORWARD_ONLY || concurrency != ResultSet.CONCUR_READ_ONLY) {
            throw BaseConnection.unsupported("scrollable or updatable result sets");
        }
    }

    @Override
    public String nativeSQL(String sql) {
        return sql;
    }

    @Override
    public void setAutoCommit(boolean value) throws SQLException {
        checkOpen();
        if (value == autoCommit) {
            return;
        }
        execute(value ? "COMMIT" : "BEGIN TRANSACTION");
        autoCommit = value;
    }

    @Override
    public boolean getAutoCommit() throws SQLException {
        checkOpen();
        return autoCommit;
    }

    @Override
    public void commit() throws SQLException {
        endTransaction("COMMIT");
    }

    @Override
    public void rollback() throws SQLException {
        endTransaction("ROLLBACK");
    }

    private void endTransaction(String sql) throws SQLException {
        checkOpen();
        if (autoCommit) {
            throw new SQLException("trexsql: " + sql + " while in auto-commit mode");
        }
        execute(sql);
        execute("BEGIN TRANSACTION");
    }

    @Override
    public void close() {
        if (!closed) {
            closed = true;
            NativeEngine.close(db);
        }
    }

    @Override
    public boolean isClosed() {
        return closed;
    }

    @Override
    public boolean isValid(int timeout) {
        if (closed) {
            return false;
        }
        try {
            query("SELECT 1");
            return true;
        } catch (SQLException e) {
            return false;
        }
    }

    @Override
    public DatabaseMetaData getMetaData() throws SQLException {
        checkOpen();
        return new TrexsqlDatabaseMetaData(this);
    }

    @Override
    public void setReadOnly(boolean readOnly) {
    }

    @Override
    public boolean isReadOnly() {
        return false;
    }

    @Override
    public void setCatalog(String catalog) {
    }

    @Override
    public String getCatalog() {
        return null;
    }

    @Override
    public void setSchema(String schema) {
    }

    @Override
    public String getSchema() {
        return null;
    }

    @Override
    public void setTransactionIsolation(int level) {
    }

    @Override
    public int getTransactionIsolation() {
        return Connection.TRANSACTION_SERIALIZABLE;
    }

    @Override
    public SQLWarning getWarnings() {
        return null;
    }

    @Override
    public void clearWarnings() {
    }

    @Override
    public void setHoldability(int holdability) {
    }

    @Override
    public int getHoldability() {
        return ResultSet.CLOSE_CURSORS_AT_COMMIT;
    }

    @Override
    public Map<String, Class<?>> getTypeMap() {
        return Collections.emptyMap();
    }

    @Override
    public void setClientInfo(String name, String value) throws SQLClientInfoException {
    }

    @Override
    public void setClientInfo(Properties properties) throws SQLClientInfoException {
    }

    @Override
    public String getClientInfo(String name) {
        return null;
    }

    @Override
    public Properties getClientInfo() {
        return new Properties();
    }

    @Override
    public void setNetworkTimeout(Executor executor, int milliseconds) {
    }

    @Override
    public int getNetworkTimeout() {
        return 0;
    }

    @Override
    public void abort(Executor executor) {
        close();
    }

    @Override
    public <T> T unwrap(Class<T> iface) throws SQLException {
        if (iface.isInstance(this)) {
            return iface.cast(this);
        }
        throw new SQLException("trexsql: not a wrapper for " + iface.getName());
    }

    @Override
    public boolean isWrapperFor(Class<?> iface) {
        return iface.isInstance(this);
    }
}
