package org.trex.jdbc;

import java.math.BigDecimal;
import java.sql.BatchUpdateException;
import java.sql.Connection;
import java.sql.Date;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.sql.Time;
import java.sql.Timestamp;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Calendar;
import java.util.List;
import java.util.Locale;

/**
 * Both {@link java.sql.Statement} and {@link java.sql.PreparedStatement}:
 * {@code sql == null} for a plain statement. Parameters are bound client-side
 * as SQL literals.
 */
final class TrexsqlStatement extends BaseStatement {

    private final TrexsqlConnection conn;
    private final String sql;
    private final List<Object> params = new ArrayList<>();
    private final List<String> batch = new ArrayList<>();
    private TrexsqlResultSet resultSet;
    private int updateCount = -1;
    private int maxRows;
    private int fetchSize;
    private int queryTimeout;
    private boolean closed;
    private boolean closeOnCompletion;

    TrexsqlStatement(TrexsqlConnection conn, String sql) {
        this.conn = conn;
        this.sql = sql;
    }

    private void checkOpen() throws SQLException {
        if (closed) {
            throw new SQLException("trexsql: statement is closed");
        }
        conn.checkOpen();
    }

    private String prepared() throws SQLException {
        if (sql == null) {
            throw new SQLException("trexsql: not a prepared statement");
        }
        return Sql.bind(sql, params);
    }

    /** Runs one statement; returns true when it produced a result set. */
    private boolean run(String text) throws SQLException {
        checkOpen();
        closeResult();
        updateCount = -1;
        if (Sql.returnsRows(text)) {
            resultSet = new TrexsqlResultSet(this, conn.query(text), maxRows);
            return true;
        }
        try {
            updateCount = countOf(conn.query(text));
        } catch (SQLException e) {
            String msg = e.getMessage() == null ? "" : e.getMessage().toLowerCase(Locale.ROOT);
            if (!msg.contains("multiple statements")) {
                throw e;
            }
            conn.execute(text);
            updateCount = 0;
        }
        return false;
    }

    // DML reports its row count as a single "Count" value; DDL reports nothing.
    private static int countOf(NativeEngine.Rows r) {
        if (r.names.length == 1 && !r.rows.isEmpty() && r.rows.get(0)[0] instanceof Number) {
            return ((Number) r.rows.get(0)[0]).intValue();
        }
        return 0;
    }

    private void closeResult() {
        if (resultSet != null) {
            resultSet.closeQuietly();
            resultSet = null;
        }
    }

    void resultClosed() throws SQLException {
        if (closeOnCompletion) {
            close();
        }
    }

    // --- Statement ---

    @Override
    public ResultSet executeQuery(String text) throws SQLException {
        if (!run(text)) {
            throw new SQLException("trexsql: statement did not return a result set");
        }
        return resultSet;
    }

    @Override
    public int executeUpdate(String text) throws SQLException {
        if (run(text)) {
            closeResult();
            throw new SQLException("trexsql: executeUpdate on a statement that returns rows");
        }
        return updateCount;
    }

    @Override
    public boolean execute(String text) throws SQLException {
        return run(text);
    }

    @Override
    public boolean execute(String text, int autoGeneratedKeys) throws SQLException {
        return execute(text);
    }

    @Override
    public int executeUpdate(String text, int autoGeneratedKeys) throws SQLException {
        return executeUpdate(text);
    }

    @Override
    public ResultSet getResultSet() {
        return resultSet;
    }

    @Override
    public int getUpdateCount() {
        return updateCount;
    }

    @Override
    public boolean getMoreResults() {
        closeResult();
        updateCount = -1;
        return false;
    }

    @Override
    public boolean getMoreResults(int current) {
        return getMoreResults();
    }

    @Override
    public void addBatch(String text) throws SQLException {
        checkOpen();
        batch.add(text);
    }

    @Override
    public void clearBatch() {
        batch.clear();
    }

    @Override
    public int[] executeBatch() throws SQLException {
        checkOpen();
        int[] counts = new int[batch.size()];
        try {
            for (int i = 0; i < batch.size(); i++) {
                try {
                    run(batch.get(i));
                } catch (SQLException e) {
                    throw new BatchUpdateException(e.getMessage(), e.getSQLState(), Arrays.copyOf(counts, i), e);
                }
                closeResult();
                counts[i] = Math.max(updateCount, 0);
            }
            return counts;
        } finally {
            batch.clear();
        }
    }

    @Override
    public void close() {
        if (!closed) {
            closeResult();
            closed = true;
        }
    }

    @Override
    public boolean isClosed() {
        return closed;
    }

    @Override
    public void closeOnCompletion() {
        closeOnCompletion = true;
    }

    @Override
    public boolean isCloseOnCompletion() {
        return closeOnCompletion;
    }

    @Override
    public Connection getConnection() {
        return conn;
    }

    @Override
    public void cancel() {
        // Statements run synchronously; there is nothing in flight to cancel.
    }

    @Override
    public void setMaxRows(int max) {
        maxRows = Math.max(max, 0);
    }

    @Override
    public int getMaxRows() {
        return maxRows;
    }

    @Override
    public void setFetchSize(int rows) {
        fetchSize = rows;
    }

    @Override
    public int getFetchSize() {
        return fetchSize;
    }

    @Override
    public void setFetchDirection(int direction) throws SQLException {
        if (direction != ResultSet.FETCH_FORWARD) {
            throw unsupported("fetch direction");
        }
    }

    @Override
    public int getFetchDirection() {
        return ResultSet.FETCH_FORWARD;
    }

    @Override
    public void setQueryTimeout(int seconds) {
        queryTimeout = seconds;
    }

    @Override
    public int getQueryTimeout() {
        return queryTimeout;
    }

    @Override
    public void setEscapeProcessing(boolean enable) {
    }

    @Override
    public void setMaxFieldSize(int max) {
    }

    @Override
    public int getMaxFieldSize() {
        return 0;
    }

    @Override
    public void setPoolable(boolean poolable) {
    }

    @Override
    public boolean isPoolable() {
        return false;
    }

    @Override
    public void setCursorName(String name) {
    }

    @Override
    public int getResultSetType() {
        return ResultSet.TYPE_FORWARD_ONLY;
    }

    @Override
    public int getResultSetConcurrency() {
        return ResultSet.CONCUR_READ_ONLY;
    }

    @Override
    public int getResultSetHoldability() {
        return ResultSet.CLOSE_CURSORS_AT_COMMIT;
    }

    @Override
    public SQLWarning getWarnings() {
        return null;
    }

    @Override
    public void clearWarnings() {
    }

    @Override
    public <T> T unwrap(Class<T> iface) throws SQLException {
        if (iface.isInstance(this)) {
            return iface.cast(this);
        }
        throw new SQLException("trexsql: not a wrapper for " + iface.getName());
    }

    @Override
    public boolean isWrapperFor(Class<?> iface) {
        return iface.isInstance(this);
    }

    // --- PreparedStatement ---

    @Override
    public ResultSet executeQuery() throws SQLException {
        return executeQuery(prepared());
    }

    @Override
    public int executeUpdate() throws SQLException {
        return executeUpdate(prepared());
    }

    @Override
    public boolean execute() throws SQLException {
        return execute(prepared());
    }

    @Override
    public void addBatch() throws SQLException {
        addBatch(prepared());
    }

    @Override
    public void clearParameters() {
        params.clear();
    }

    private void set(int index, Object value) throws SQLException {
        checkOpen();
        if (index < 1) {
            throw new SQLException("trexsql: parameter index " + index + " out of range");
        }
        while (params.size() < index) {
            params.add(null);
        }
        params.set(index - 1, value);
    }

    @Override
    public void setNull(int index, int sqlType) throws SQLException {
        set(index, null);
    }

    @Override
    public void setNull(int index, int sqlType, String typeName) throws SQLException {
        set(index, null);
    }

    @Override
    public void setBoolean(int index, boolean x) throws SQLException {
        set(index, x);
    }

    @Override
    public void setByte(int index, byte x) throws SQLException {
        set(index, x);
    }

    @Override
    public void setShort(int index, short x) throws SQLException {
        set(index, x);
    }

    @Override
    public void setInt(int index, int x) throws SQLException {
        set(index, x);
    }

    @Override
    public void setLong(int index, long x) throws SQLException {
        set(index, x);
    }

    @Override
    public void setFloat(int index, float x) throws SQLException {
        set(index, x);
    }

    @Override
    public void setDouble(int index, double x) throws SQLException {
        set(index, x);
    }

    @Override
    public void setBigDecimal(int index, BigDecimal x) throws SQLException {
        set(index, x);
    }

    @Override
    public void setString(int index, String x) throws SQLException {
        set(index, x);
    }

    @Override
    public void setNString(int index, String x) throws SQLException {
        set(index, x);
    }

    @Override
    public void setBytes(int index, byte[] x) throws SQLException {
        set(index, x);
    }

    @Override
    public void setDate(int index, Date x) throws SQLException {
        set(index, x);
    }

    @Override
    public void setDate(int index, Date x, Calendar cal) throws SQLException {
        set(index, x);
    }

    @Override
    public void setTime(int index, Time x) throws SQLException {
        set(index, x);
    }

    @Override
    public void setTime(int index, Time x, Calendar cal) throws SQLException {
        set(index, x);
    }

    @Override
    public void setTimestamp(int index, Timestamp x) throws SQLException {
        set(index, x);
    }

    @Override
    public void setTimestamp(int index, Timestamp x, Calendar cal) throws SQLException {
        set(index, x);
    }

    @Override
    public void setObject(int index, Object x) throws SQLException {
        set(index, x);
    }

    @Override
    public void setObject(int index, Object x, int targetSqlType) throws SQLException {
        set(index, x);
    }

    @Override
    public void setObject(int index, Object x, int targetSqlType, int scaleOrLength) throws SQLException {
        set(index, x);
    }
}
