Deno.test("openapi: reserved parameters, per-column rowFilters and body params", () => {
  const doc = spec();
  const params = doc.parameters as Record<string, Record<string, unknown>>;
  for (const name of ["preferParams", "preferReturn", "preferCount", "preferPost", "select", "on_conflict", "order", "range", "rangeUnit", "offset", "limit"]) {
    assertEquals(name in params, true, `missing parameter def ${name}`);
  }
  assertEquals(params.preferReturn.enum, ["return=representation", "return=minimal", "return=none"]);
  assertEquals(params.rangeUnit.default, "items");
  assertEquals(params.select, { name: "select", description: "Filtering Columns", required: false, in: "query", type: "string" });
  assertEquals(params["rowFilter.projects.id"], { name: "id", description: "the id", required: false, in: "query", type: "string" });
  assertEquals(params["body.projects"], {
    name: "projects",
    description: "projects",
    required: false,
    in: "body",
    schema: { $ref: "#/definitions/projects" },
  });
});

Deno.test("openapi: table paths — writable tables get all verbs, read-only just GET", () => {
  const doc = spec();
  const paths = doc.paths as Record<string, Record<string, Record<string, unknown>>>;
  assertEquals(Object.keys(paths), ["/", "/projects", "/stats", "/rpc/add_them"]);
  assertEquals(Object.keys(paths["/projects"]), ["get", "post", "patch", "delete"]);
  assertEquals(Object.keys(paths["/stats"]), ["get"]);
  const getOp = paths["/projects"].get;
  assertEquals(getOp.tags, ["projects"]);
  assertEquals(getOp.summary, "All projects");
  assertEquals(getOp.description, "Second line of description");
  assertEquals(getOp.responses, {
    "200": { description: "OK", schema: { items: { $ref: "#/definitions/projects" }, type: "array" } },
    "206": { description: "Partial Content" },
  });
  const getParams = getOp.parameters as { $ref: string }[];
  assertEquals(getParams[0], { $ref: "#/parameters/rowFilter.projects.id" });
  assertEquals(getParams[getParams.length - 1], { $ref: "#/parameters/preferCount" });
  assertEquals((paths["/projects"].post.parameters as unknown[])[0], { $ref: "#/parameters/body.projects" });
  assertEquals(paths["/projects"].post.responses, { "201": { description: "Created" } });
  assertEquals(paths["/projects"].delete.responses, { "204": { description: "No Content" } });
  // root path item
  assertEquals(paths["/"].get.summary, "OpenAPI description (this document)");
  assertEquals(paths["/"].get.produces, ["application/openapi+json", "application/json"]);
});

Deno.test("openapi: rpc paths — GET query params (incl. variadic) and POST args body", () => {
  const doc = spec();
  const paths = doc.paths as Record<string, Record<string, Record<string, unknown>>>;
  const rpc = paths["/rpc/add_them"];
  assertEquals(Object.keys(rpc), ["get", "post"]);
  assertEquals(rpc.get.tags, ["(rpc) add_them"]);
  assertEquals(rpc.get.summary, "adds them");
  assertEquals(rpc.get.description, "details here");
  assertEquals(rpc.get.produces, [
    "application/json",
    "application/vnd.pgrst.object+json;nulls=stripped",
    "application/vnd.pgrst.object+json",
  ]);
  const getParams = rpc.get.parameters as Record<string, unknown>[];
  assertEquals(getParams[0], { name: "a", required: true, in: "query", format: "integer", type: "integer" });
  assertEquals(getParams[2], {
    name: "v",
    required: false,
    in: "query",
    type: "array",
    items: { format: "text", type: "string" },
    collectionFormat: "multi",
  });
  const postParams = rpc.post.parameters as Record<string, unknown>[];
  assertEquals(postParams[1], { $ref: "#/parameters/preferParams" });
  const args = postParams[0] as { schema: Record<string, unknown> };
  assertEquals(args.schema.type, "object");
  assertEquals(args.schema.required, ["a"]);
  assertEquals((args.schema.properties as Record<string, unknown>).a, { format: "integer", type: "integer" });
});

Deno.test("openapi: empty properties/parameters are omitted (swagger2 omits mempty fields)", () => {
  // swagger2's sopSwaggerGenericToJSON drops fields equal to their mempty
  // default: a column-less relation has NO "properties" key and a paramless
  // routine's GET operation has NO "parameters" key.
  const bare: Table = { ...stats, name: "bare", columns: [] };
  const noArgs: Routine = { ...addThem, name: "no_args", description: null, params: [] };
  const doc = JSON.parse(encodeOpenApi(conf(), rels, [bare], [noArgs], null));
  const defs = doc.definitions as Record<string, Record<string, unknown>>;
  assertEquals("properties" in defs.bare, false);
  assertEquals(defs.bare.type, "object");
  const rpc = (doc.paths as Record<string, Record<string, Record<string, unknown>>>)["/rpc/no_args"];
  assertEquals("parameters" in rpc.get, false);
  // POST still carries the args body + preferParams, with an empty schema
  const postParams = rpc.post.parameters as { schema?: Record<string, unknown> }[];
  assertEquals(postParams.length, 2);
  assertEquals("properties" in (postParams[0].schema as Record<string, unknown>), false);
});

