Deno.test("openapi: table definitions carry typed properties, PK/FK notes, enums and defaults", () => {
  const doc = spec();
  const defs = doc.definitions as Record<string, Record<string, unknown>>;
  const def = defs.projects;
  assertEquals(def.type, "object");
  assertEquals(def.description, "All projects\n\nSecond line of description");
  assertEquals(def.required, ["id"]); // not-null columns
  const props = def.properties as Record<string, Record<string, unknown>>;
  assertEquals(props.id, {
    description: "the id\n\nNote:\nThis is a Primary Key.<pk/>",
    format: "integer",
    type: "integer",
  });
  assertEquals(props.client_id.description, [
    "Note:",
    "This is a Foreign Key to `clients.id`.<fk table='clients' column='id'/>",
  ].join("\n"));
  assertEquals(props.name, { default: "anon", format: "character varying", maxLength: 64, type: "string" });
  assertEquals(props.tags, { format: "text[]", type: "array", items: { type: "string" } });
  assertEquals(props.status, { enum: ["open", "closed"], format: "text", type: "string" });
  // json/jsonb have a format but no swagger type
  assertEquals(props.data, { format: "jsonb" });
  // the view definition has no required entries
  assertEquals("required" in defs.stats, false);
});

Deno.test("openapi: toSwaggerType/parseDefault corner cases", () => {
  assertEquals(toSwaggerType("double precision"), "number");
  assertEquals(toSwaggerType("integer[]"), "array");
  assertEquals(toSwaggerType("tsrange"), "string");
  assertEquals(toSwaggerType("jsonb"), undefined);
  assertEquals(parseDefault("text", "'hi'::text"), '"hi"');
  assertEquals(parseDefault("integer", "42"), "42");
});

