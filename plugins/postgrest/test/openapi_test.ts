Deno.test("openapi: top-level swagger fields, info from the schema comment", () => {
  const doc = spec();
  assertEquals(doc.swagger, "2.0");
  assertEquals(doc.basePath, "/");
  assertEquals(doc.schemes, ["http"]);
  assertEquals(doc.host, "0.0.0.0:3000"); // server-host default "!4" escapes
  assertEquals(doc.info, { description: "longer description", title: "My API", version: prettyVersion });
  assertEquals(doc.externalDocs, {
    description: "PostgREST Documentation",
    url: `https://postgrest.org/en/${docsVersion}/references/api.html`,
  });
  assertEquals(doc.produces, doc.consumes);
  assertEquals((doc.produces as string[])[0], "application/json");
  // no security definitions unless openapi-security-active
  assertEquals("securityDefinitions" in doc, false);
  assertEquals("security" in doc, false);
});

Deno.test("openapi: defaults for title/description when there is no schema comment", () => {
  const doc = spec({}, null);
  assertEquals(doc.info, {
    description: "This is a dynamic API generated by PostgREST",
    title: "PostgREST API",
    version: prettyVersion,
  });
});

Deno.test("openapi: single-line schema comment yields an EMPTY info.description", () => {
  // OpenAPI.hs: breakOn "\n" gives (title, Just "") — so the "dynamic API"
  // fallback does NOT apply (MultipleSchemaSpec "builds openapi for a valid
  // schema": COMMENT ON SCHEMA v1 IS 'v1 schema' -> description "").
  const doc = spec({}, "v1 schema");
  assertEquals(doc.info, { description: "", title: "v1 schema", version: prettyVersion });
  // ...while path items filter the empty description out (mfilter (/=""))
  const single = JSON.parse(
    encodeOpenApi(conf(), rels, [{ ...projects, description: "one liner" }], [], "v1 schema"),
  );
  const getOp = (single.paths as Record<string, Record<string, Record<string, unknown>>>)["/projects"].get;
  assertEquals(getOp.summary, "one liner");
  assertEquals("description" in getOp, false);
});

Deno.test("openapi: an empty schema omits the definitions key entirely", () => {
  // swagger2's ToJSON omits mempty maps; the oracle's nonexistent-schema
  // OpenAPI output has no "definitions" key at all (ErrorSpec.nonExistentSchema).
  const doc = JSON.parse(encodeOpenApi(conf(), new Map(), [], [], null));
  assertEquals("definitions" in doc, false);
  assertEquals(Object.keys(doc.paths as Record<string, unknown>), ["/"]);
});

Deno.test("openapi: proxy uri drives scheme/host/port/basePath", () => {
  const doc = spec({ PGRST_OPENAPI_SERVER_PROXY_URI: "https://postgrest.com:8443/openapi" });
  assertEquals(doc.schemes, ["https"]);
  assertEquals(doc.host, "postgrest.com:8443");
  assertEquals(doc.basePath, "/openapi");
  // default ports per scheme
  assertEquals(proxyUri(conf({ PGRST_OPENAPI_SERVER_PROXY_URI: "https://example.com/base" })), [
    "https",
    "example.com",
    443,
    "/base",
  ]);
  // malformed proxy uris fall back to server-host/server-port
  assertEquals(pickProxy("ftp://example.com"), null);
  assertEquals(pickProxy("http://user:pw@example.com"), null);
  assertEquals(pickProxy("http://example.com/?query=1"), null);
  assertEquals(pickProxy("not a uri"), null);
  const fallback = spec({ PGRST_OPENAPI_SERVER_PROXY_URI: "ftp://example.com", PGRST_SERVER_HOST: "myhost", PGRST_SERVER_PORT: "4000" });
  assertEquals(fallback.host, "myhost:4000");
});

