const infoCache: SchemaCache = {
  tables: new Map([
    ["test.projects", projects],
    ["test.stats", stats],
    ["test.nopk", { ...projects, name: "nopk", pkCols: [] }],
    ["test.insert_only", { ...projects, name: "insert_only", updatable: false, deletable: false }],
  ]),
  relationships: new Map(),
  routines: new Map(),
  representations: new Map(),
  mediaHandlers: [],
  timezones: new Set(),
};

Deno.test("OPTIONS: per-table Allow follows insertable/updatable/deletable and the PK for PUT", () => {
  const allow = (name: string) => infoIdentResponse(qi(name), infoCache).headers.get("Allow");
  assertEquals(allow("projects"), "OPTIONS,GET,HEAD,POST,PUT,PATCH,DELETE");
  assertEquals(allow("stats"), "OPTIONS,GET,HEAD");
  // no PK → no PUT
  assertEquals(allow("nopk"), "OPTIONS,GET,HEAD,POST,PATCH,DELETE");
  // insertable but not updatable → no PUT/PATCH
  assertEquals(allow("insert_only"), "OPTIONS,GET,HEAD,POST");
  const res = infoIdentResponse(qi("projects"), infoCache);
  assertEquals(res.status, 200);
  assertEquals(res.headers.get("Access-Control-Allow-Origin"), "*");
  // unknown table → 404
  const err = assertThrows(() => infoIdentResponse(qi("missing"), infoCache)) as PgrstError;
  assertEquals(err.status, 404);
});

Deno.test("OPTIONS: routines allow POST always, GET/HEAD only when not volatile; root is read-only", () => {
  assertEquals(infoProcResponse(addThem).headers.get("Allow"), "OPTIONS,GET,HEAD,POST");
  assertEquals(infoProcResponse({ ...addThem, volatility: "volatile" }).headers.get("Allow"), "OPTIONS,POST");
  assertEquals(infoRootResponse().headers.get("Allow"), "OPTIONS,GET,HEAD");
});

Deno.test("openapi: escapeHostName maps the wildcard listen addresses", () => {
  for (const h of ["*", "*4", "!4", "*6", "!6"]) assertEquals(escapeHostName(h), "0.0.0.0");
  assertEquals(escapeHostName("example.com"), "example.com");
});

